///usr/bin/env java --source 21 "$0" "$@" ; exit $?
//
// CI test: proves `ArchHook.jar boundary-map` writes the boundary map of every blueprint, and that
// the map it writes is one the project's own `check` hook enforces.
//
// Why this test exists: until decision 0166 the single-module half of `project-files.md` § 5 was
// prose an agent followed, and the multi-module half a transcription of `forbidden_imports` — a
// blueprint whose rules derived to nothing, or to a prefix `check` never matches, generated a
// project that looked guarded and blocked nothing (the hook warns "enforcement is off" once, then
// stays silent). Nothing ran the derivation. Now the mode is the derivation, and this test holds it.
//
// What it holds, for every `<id>/<id>.yaml` under `.claude/blueprints/`:
//   - the mode exits 0 and writes `<dest>/.claude/forbidden-imports.txt` with the header and at
//     least one `<path>|<prefix>` line, no duplicate and no trailing `..`;
//   - a single-module map starts every line at `src/main/java/<package path>/`, and never forbids a
//     package from importing itself or a package it contains;
//   - a name in `dependency_rules` that matches no `packages.map` entry is reported on stderr — the
//     unresolved set is exactly UNRESOLVED below, so a typo in a blueprint fails here by name;
// and, on named cases:
//   - hexagonal (multi-module) copies `domain|org.springframework.` and `..` becomes `.`;
//   - clean-architecture-single-module gives `domain` the four framework roots, both Jackson ones,
//     and `application` none;
//   - hexagonal-single-module forbids `adapter.out.cache` → `adapter.out.persistence` and leaves
//     `adapter.in.graphql` → `adapter.in.rest` open (decision 0165);
//   - the map `check` reads blocks a file the map names (exit 2) and passes a clean one (exit 0), for
//     one single-module and one multi-module blueprint;
//   - a malformed `--package`, an unknown blueprint and a missing option exit 2 and write nothing.

import java.io.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import java.util.concurrent.TimeUnit;
import java.util.stream.*;

public class BoundaryMapTest {

    static final Path HOOK = Paths.get(".claude/hooks/ArchHook.jar").toAbsolutePath();
    static final Path REPO = Paths.get(".").toAbsolutePath().normalize();
    static final String PKG = "com.acme.shop";
    static final String SRC = "src/main/java/com/acme/shop/";

    /** Names a blueprint's `dependency_rules` use that its `packages.map` has no entry for, on purpose. */
    static final Map<String, Set<String>> UNRESOLVED = Map.of("vertical-slice", Set.of("features"));

    static int failures = 0;

    record Run(int exit, String out, String err) {}

    public static void main(String[] args) throws Exception {
        List<String> ids = blueprints();
        expect(ids.size() >= 9, "found " + ids.size() + " blueprints, expected at least nine — the scan stopped matching");

        Map<String, List<String>> maps = new TreeMap<>();
        for (String id : ids) {
            Path dest = Files.createTempDirectory("boundary-map-" + id);
            Run r = run(REPO, "boundary-map", dest.toString(), "--blueprint", id, "--package", PKG);
            Path file = dest.resolve(".claude/forbidden-imports.txt");
            if (!expect(r.exit == 0 && Files.isRegularFile(file), id + ": mode exits 0 and writes the map (exit "
                    + r.exit + ", stderr: " + r.err.strip() + ")")) continue;
            List<String> lines = Files.readAllLines(file, StandardCharsets.UTF_8);
            maps.put(id, lines);
            boolean single = !lines.stream().skip(1).allMatch(l -> !l.startsWith(SRC)) ;
            expect(lines.get(0).equals("# Generated by /init-project — blueprint: " + id + " — do not edit by hand"),
                    id + ": header names the blueprint");
            List<String> rules = lines.subList(1, lines.size());
            expect(!rules.isEmpty() && rules.stream().allMatch(l -> l.matches("[^|\\s]+\\|[A-Za-z0-9_.]+")),
                    id + ": every line is `<path>|<prefix>`");
            expect(new HashSet<>(rules).size() == rules.size(), id + ": no duplicate line");
            expect(rules.stream().noneMatch(l -> l.endsWith("..")), id + ": no ArchUnit `..` left in a prefix");
            if (single) {
                expect(rules.stream().allMatch(l -> l.startsWith(SRC)),
                        id + ": single-module lines all start at " + SRC);
                List<String> selfRef = rules.stream().filter(l -> {
                    String left = l.substring(SRC.length(), l.indexOf('|')).replace('/', '.');
                    String right = l.substring(l.indexOf('|') + 1);
                    String target = right.startsWith(PKG + ".") ? right.substring(PKG.length() + 1) : null;
                    return target != null && (target.equals(left + ".") || target.startsWith(left + ".")
                            || left.startsWith(target));
                }).toList();
                expect(selfRef.isEmpty(), id + ": a package is never forbidden its own imports " + selfRef);
            }
            Set<String> got = new TreeSet<>();
            r.err.lines().filter(l -> l.contains("matches no entry of packages.map")).forEach(l -> {
                int a = l.indexOf('`'), b = l.indexOf('`', a + 1);
                got.add(l.substring(a + 1, b));
            });
            expect(got.equals(UNRESOLVED.getOrDefault(id, Set.of())),
                    id + ": unresolved names are " + UNRESOLVED.getOrDefault(id, Set.of()) + ", got " + got);
        }

        List<String> hex = maps.getOrDefault("hexagonal", List.of());
        expect(hex.contains("domain|org.springframework."), "hexagonal: copies domain|org.springframework.");
        expect(hex.contains("domain|tools.jackson."), "hexagonal: copies domain|tools.jackson. (the second Jackson root)");

        List<String> clean = maps.getOrDefault("clean-architecture-single-module", List.of());
        for (String root : List.of("org.springframework.", "jakarta.", "com.fasterxml.jackson.", "tools.jackson.")) {
            expect(clean.contains(SRC + "domain/model|" + root), "clean-single: domain gets framework root " + root);
        }
        expect(clean.stream().noneMatch(l -> l.startsWith(SRC + "application") && l.contains("|org.springframework")),
                "clean-single: application gets no framework root");
        expect(clean.contains(SRC + "domain/model|" + PKG + ".application.usecase."),
                "clean-single: domain forbidden from application.usecase");

        List<String> hexs = maps.getOrDefault("hexagonal-single-module", List.of());
        expect(hexs.contains(SRC + "adapter/out/cache|" + PKG + ".adapter.out.persistence."),
                "hexagonal-single: adapter.out.cache forbidden from adapter.out.persistence");
        expect(hexs.stream().noneMatch(l -> l.equals(SRC + "adapter/in/graphql|" + PKG + ".adapter.in.rest.")),
                "hexagonal-single: adapter.in.graphql → adapter.in.rest stays open (0165)");
        expect(hexs.contains(SRC + "adapter/in/rest|" + PKG + ".adapter.in.graphql."),
                "hexagonal-single: adapter.in.rest forbidden from adapter.in.graphql");

        // The map is what `check` enforces — one blueprint of each layout, end to end.
        enforce("hexagonal-single-module", "adapter/out/cache",
                "package com.acme.shop.adapter.out.cache;\nimport com.acme.shop.adapter.out.persistence.OrderEntity;\nclass Bad {}\n",
                "src/main/java/com/acme/shop/adapter/out/cache/Bad.java");
        enforce("hexagonal", "domain",
                "package com.acme.shop.domain;\nimport org.springframework.stereotype.Component;\nclass Bad {}\n",
                "domain/src/main/java/com/acme/shop/domain/Bad.java");

        // Refusals: nothing written.
        refuse("a package that is no Java name", "boundary-map", "x", "--blueprint", "hexagonal", "--package", "1com..shop");
        refuse("an unknown blueprint", "boundary-map", "x", "--blueprint", "nope", "--package", PKG);
        refuse("a missing --package", "boundary-map", "x", "--blueprint", "hexagonal");

        if (failures > 0) {
            System.err.println("❌ " + failures + " case(s) failed — the boundary map of a generated project is NOT what the blueprint says.");
            System.exit(1);
        }
        System.out.println("✅ boundary-map: " + maps.size() + " blueprints derive a map, and `check` enforces it.");
    }

    static List<String> blueprints() throws IOException {
        try (Stream<Path> s = Files.list(REPO.resolve(".claude/blueprints"))) {
            return s.filter(Files::isDirectory)
                    .filter(d -> Files.isRegularFile(d.resolve(d.getFileName() + ".yaml")))
                    .map(d -> d.getFileName().toString()).sorted().toList();
        }
    }

    /** Writes the map for {@code id}, plants {@code body} at {@code rel} and a clean sibling, and runs `check` on both. */
    static void enforce(String id, String dir, String body, String rel) throws Exception {
        Path project = Files.createTempDirectory("boundary-enforce-" + id);
        Run w = run(REPO, "boundary-map", project.toString(), "--blueprint", id, "--package", PKG);
        if (!expect(w.exit == 0, id + ": map written for the enforcement case")) return;
        Path bad = project.resolve(rel);
        Files.createDirectories(bad.getParent());
        Files.writeString(bad, body, StandardCharsets.UTF_8);
        Path clean = bad.resolveSibling("Clean.java");
        Files.writeString(clean, body.lines().filter(l -> !l.startsWith("import")).collect(Collectors.joining("\n")) + "\n",
                StandardCharsets.UTF_8);
        Run b = run(project, "check", project.relativize(bad).toString());
        expect(b.exit == 2, id + ": `check` blocks a forbidden import in " + dir + " (exit " + b.exit + ")");
        Run c = run(project, "check", project.relativize(clean).toString());
        expect(c.exit == 0, id + ": `check` passes the same file without the import (exit " + c.exit + ")");
    }

    static void refuse(String what, String... modeArgs) throws Exception {
        Path dest = Files.createTempDirectory("boundary-refuse");
        String[] a = modeArgs.clone();
        a[1] = dest.toString();
        Run r = run(REPO, a);
        expect(r.exit == 2 && !Files.exists(dest.resolve(".claude/forbidden-imports.txt")),
                "refuses " + what + " with exit 2 and writes nothing (exit " + r.exit + ")");
    }

    static Run run(Path project, String... modeArgs) throws Exception {
        List<String> cmd = new ArrayList<>(List.of(
                ProcessHandle.current().info().command().orElse("java"), "-jar", HOOK.toString()));
        cmd.addAll(List.of(modeArgs));
        ProcessBuilder pb = new ProcessBuilder(cmd);
        pb.environment().put("CLAUDE_PROJECT_DIR", project.toString());
        Process p = pb.start();
        p.getOutputStream().close();
        if (!p.waitFor(60, TimeUnit.SECONDS)) {
            p.destroyForcibly();
            return new Run(-1, "", "timeout");
        }
        return new Run(p.exitValue(),
                new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8),
                new String(p.getErrorStream().readAllBytes(), StandardCharsets.UTF_8));
    }

    static boolean expect(boolean ok, String name) {
        if (ok) { System.out.println("  ✓ " + name); }
        else { System.out.println("  ✗ " + name); failures++; }
        return ok;
    }
}
